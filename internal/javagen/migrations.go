package javagen

import (
	"fmt"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"github.com/Lumos-Labs-HQ/flash/internal/gencommon"
)

func (g *Generator) generateMigrations() error {
	migrations, err := gencommon.LoadEmbeddedMigrations(g.Config.MigrationsPath)
	if err != nil {
		return err
	}
	pkg := javaPackage(&g.Config.Gen.Java)
	var w strings.Builder
	w.WriteString("// Code generated by FlashORM. DO NOT EDIT.\npackage " + pkg + ";\n\nimport java.sql.*;\nimport java.util.*;\n\npublic final class FlashMigrations {\n")
	w.WriteString("  private record Migration(String id, String name, String checksum, List<String> statements) {}\n  private static final List<Migration> MIGRATIONS = List.of(\n")
	for i, m := range migrations {
		comma := ","
		if i == len(migrations)-1 {
			comma = ""
		}
		w.WriteString(fmt.Sprintf("    new Migration(%s, %s, %s, List.of(", strconv.Quote(m.ID), strconv.Quote(m.Name), strconv.Quote(m.Checksum)))
		for j, s := range m.Statements {
			if j > 0 {
				w.WriteString(", ")
			}
			w.WriteString(strconv.Quote(s))
		}
		w.WriteString("))" + comma + "\n")
	}
	w.WriteString("  );\n\n  /** Applies embedded migrations without invoking the Flash binary. */\n  public static void FlashInitMigrate(Connection conn) throws SQLException {\n    try (Statement st = conn.createStatement()) { st.execute(\"CREATE TABLE IF NOT EXISTS _flash_migrations (id VARCHAR(255) PRIMARY KEY, checksum VARCHAR(64) NOT NULL, finished_at TIMESTAMP, migration_name VARCHAR(255) NOT NULL, started_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)\"); }\n    Map<String,String> known = new HashMap<>();\n    try (Statement st = conn.createStatement(); ResultSet rs = st.executeQuery(\"SELECT id, checksum FROM _flash_migrations WHERE finished_at IS NOT NULL\")) { while (rs.next()) known.put(rs.getString(1), rs.getString(2)); }\n    for (Migration migration : MIGRATIONS) { if (known.containsKey(migration.id())) { if (!known.get(migration.id()).equals(migration.checksum())) throw new SQLException(\"applied migration \" + migration.id() + \" checksum mismatch\"); continue; } boolean oldAuto = conn.getAutoCommit(); conn.setAutoCommit(false); try { for (String sql : migration.statements()) try (Statement st = conn.createStatement()) { st.execute(sql); } try (PreparedStatement ps = conn.prepareStatement(\"INSERT INTO _flash_migrations (id, migration_name, checksum, started_at, finished_at) VALUES (?, ?, ?, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP)\")) { ps.setString(1, migration.id()); ps.setString(2, migration.name()); ps.setString(3, migration.checksum()); ps.executeUpdate(); } conn.commit(); } catch (SQLException e) { conn.rollback(); throw e; } finally { conn.setAutoCommit(oldAuto); } }\n  }\n}\n")
	return os.WriteFile(filepath.Join(g.Config.Gen.Java.Out, "FlashMigrations.java"), []byte(w.String()), 0644)
}
