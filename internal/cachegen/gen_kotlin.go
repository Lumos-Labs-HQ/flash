// GenerateKotlinCache generates FlashCache.kt using Lettuce (Redis)
func GenerateKotlinCache(cfg *config.CacheConfig, packageName string) string {
	var w strings.Builder
	w.WriteString("// Code generated by FlashORM. DO NOT EDIT.\n\n")
	if packageName != "" {
		w.WriteString(fmt.Sprintf("package %s\n\n", packageName))
	}
	w.WriteString(fmt.Sprintf(`import io.lettuce.core.RedisClient
import io.lettuce.core.api.sync.RedisCommands
import com.google.gson.Gson

object FlashCache {
    private val client = RedisClient.create(System.getenv("%s") ?: "redis://localhost:6379")
    private val connection = client.connect()
    private val commands: RedisCommands<String, String> = connection.sync()
    private val gson = Gson()
    private const val PREFIX = "%s"

    fun <T> get(key: String, clazz: Class<T>): T? {
        val data = commands.get("$PREFIX:$key") ?: return null
        return gson.fromJson(data, clazz)
    }

    fun <T> set(key: String, value: T, ttlSeconds: Long, tags: List<String> = emptyList()) {
        val fullKey = "$PREFIX:$key"
        commands.setex(fullKey, ttlSeconds, gson.toJson(value))
        for (tag in tags) {
            commands.sadd("$PREFIX:tag:$tag", key)
        }
    }

    fun del(key: String) {
        commands.del("$PREFIX:$key")
    }

    fun purgeByTag(tag: String) {
        val tagKey = "$PREFIX:tag:$tag"
        val keys = commands.smembers(tagKey)
        for (k in keys) {
            commands.del("$PREFIX:$k")
        }
        commands.del(tagKey)
    }

    fun purgeByPrefix(prefix: String) {
        val pattern = "$PREFIX:$prefix*"
        var cursor = io.lettuce.core.ScanCursor.INITIAL
        do {
            val result = commands.scan(cursor, io.lettuce.core.ScanArgs().match(pattern).limit(100))
            for (key in result.keys) {
                commands.del(key)
            }
            cursor = result
        } while (!cursor.isFinished)
    }

    fun close() {
        connection.close()
        client.shutdown()
    }
}
`, cfg.RedisURLEnv, cfg.Prefix))
	return w.String()
}

// GenerateKotlinCacheAccessors generates named cache accessor objects
func GenerateKotlinCacheAccessors(caches []*CacheInfo, packageName string) string {
	if len(caches) == 0 {
		return ""
	}

	var w strings.Builder
	w.WriteString("// Code generated by FlashORM. DO NOT EDIT.\n\n")
	if packageName != "" {
		w.WriteString(fmt.Sprintf("package %s\n\n", packageName))
	}

	// Generate typed CacheTag enum
	allTags := collectUniqueTags(caches)
	if len(allTags) > 0 {
		w.WriteString("/** Available cache tags for type-safe purging. */\n")
		w.WriteString("enum class CacheTag(val value: String) {\n")
		for i, tag := range allTags {
			suffix := ","
			if i == len(allTags)-1 {
				suffix = ";"
			}
			w.WriteString(fmt.Sprintf("    %s(\"%s\")%s\n", strings.ToUpper(tag), tag, suffix))
		}
		w.WriteString("\n    /** Purge all cache entries associated with this tag. */\n")
		w.WriteString("    fun purge() = FlashCache.purgeByTag(value)\n")
		w.WriteString("}\n\n")
	}

	for _, c := range caches {
		ttlSec := ParseTTL(c.TTL)

		var paramList, keyParts []string
		for _, p := range c.KeyParams {
			paramList = append(paramList, fmt.Sprintf("%s: Any", p))
			keyParts = append(keyParts, fmt.Sprintf("$%s", p))
		}
		paramStr := strings.Join(paramList, ", ")
		keyExpr := fmt.Sprintf(`"%s:%s"`, c.CacheName, strings.Join(keyParts, ":"))
		if len(keyParts) == 0 {
			keyExpr = fmt.Sprintf(`"%s"`, c.CacheName)
		}

		tagsLiteral := "emptyList()"
		if len(c.Tags) > 0 {
			quoted := make([]string, len(c.Tags))
			for i, t := range c.Tags {
				quoted[i] = fmt.Sprintf(`"%s"`, t)
			}
			tagsLiteral = fmt.Sprintf("listOf(%s)", strings.Join(quoted, ", "))
		}

		w.WriteString(fmt.Sprintf("object %s {\n", c.CacheName))
		w.WriteString(fmt.Sprintf("    fun <T> get(%s, clazz: Class<T>): T? {\n", paramStr))
		w.WriteString(fmt.Sprintf("        return FlashCache.get(%s, clazz)\n", keyExpr))
		w.WriteString("    }\n\n")
		w.WriteString(fmt.Sprintf("    fun <T> set(%s, value: T) {\n", paramStr))
		w.WriteString(fmt.Sprintf("        FlashCache.set(%s, value, %d, %s)\n", keyExpr, ttlSec, tagsLiteral))
		w.WriteString("    }\n\n")
		w.WriteString(fmt.Sprintf("    fun del(%s) {\n", paramStr))
		w.WriteString(fmt.Sprintf("        FlashCache.del(%s)\n", keyExpr))
		w.WriteString("    }\n\n")
		w.WriteString("    fun purge() {\n")
		w.WriteString(fmt.Sprintf("        FlashCache.purgeByPrefix(\"%s:\")\n", c.CacheName))
		w.WriteString("    }\n")
		w.WriteString("}\n\n")
	}
	return w.String()
}
