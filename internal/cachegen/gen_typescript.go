// GenerateTypeScriptCache generates the cache.ts file
func GenerateTypeScriptCache(cfg *config.CacheConfig) string {
	var w strings.Builder
	w.WriteString("// Code generated by FlashORM. DO NOT EDIT.\n\n")
	w.WriteString(fmt.Sprintf(`import Redis from "ioredis";

const redis = new Redis(process.env.%s || "redis://localhost:6379");
const PREFIX = "%s";

export class FlashCache {
    async get<T>(key: string): Promise<T | null> {
        const data = await redis.get(PREFIX + ":" + key);
        return data ? JSON.parse(data) as T : null;
    }

    async set<T>(key: string, value: T, ttlMs: number, tags: string[] = []): Promise<void> {
        const fullKey = PREFIX + ":" + key;
        await redis.set(fullKey, JSON.stringify(value), "PX", ttlMs);
        for (const tag of tags) {
            await redis.sadd(PREFIX + ":tag:" + tag, key);
        }
    }

    async del(key: string): Promise<void> {
        await redis.del(PREFIX + ":" + key);
    }

    async purgeByTag(tag: string): Promise<void> {
        const tagKey = PREFIX + ":tag:" + tag;
        const keys = await redis.smembers(tagKey);
        for (const k of keys) {
            await redis.del(PREFIX + ":" + k);
        }
        await redis.del(tagKey);
    }

    async purgeByPrefix(prefix: string): Promise<void> {
        const pattern = PREFIX + ":" + prefix + "*";
        const keys = await redis.keys(pattern);
        if (keys.length > 0) {
            await redis.del(...keys);
        }
    }

    async close(): Promise<void> {
        await redis.quit();
    }
}

export const cache = new FlashCache();
`, cfg.RedisURLEnv, cfg.Prefix))
	return w.String()
}

// GenerateTypeScriptCacheAccessors generates named cache accessors for TypeScript
func GenerateTypeScriptCacheAccessors(caches []*CacheInfo) string {
	if len(caches) == 0 {
		return ""
	}

	var w strings.Builder
	w.WriteString("// Code generated by FlashORM. DO NOT EDIT.\n\n")
	w.WriteString("import { cache } from \"./cache\";\n\n")

	// Generate typed CacheTag enum
	allTags := collectUniqueTags(caches)
	if len(allTags) > 0 {
		w.WriteString("/** Available cache tags for type-safe purging. */\n")
		w.WriteString("export enum CacheTag {\n")
		// Distinct tags can PascalCase to the same member name ("user-posts" and
		// "user_posts" -> "UserPosts"); dedupe so the enum has no duplicate member.
		memberNames := make([]string, len(allTags))
		for i, tag := range allTags {
			memberNames[i] = utils.ToPascalCase(tag)
		}
		memberNames = dedupeNames(memberNames)
		for i, tag := range allTags {
			w.WriteString(fmt.Sprintf("  %s = \"%s\",\n", memberNames[i], tag))
		}
		w.WriteString("}\n\n")
		w.WriteString("/** Purge all cache entries associated with a tag. */\n")
		w.WriteString("export async function purgeTag(tag: CacheTag): Promise<void> {\n")
		w.WriteString("  await cache.purgeByTag(tag);\n")
		w.WriteString("}\n\n")
	}

	for _, c := range caches {
		ttlMs := ParseTTL(c.TTL) * 1000

		var paramList, keyParts []string
		for _, p := range c.KeyParams {
			sp := safeParam(p, tsReserved)
			paramList = append(paramList, fmt.Sprintf("%s: string | number", sp))
			keyParts = append(keyParts, fmt.Sprintf("${%s}", sp))
		}
		paramStr := strings.Join(paramList, ", ")
		keyExpr := fmt.Sprintf("`%s:%s`", c.CacheName, strings.Join(keyParts, ":"))
		if len(keyParts) == 0 {
			keyExpr = fmt.Sprintf(`"%s"`, c.CacheName)
		}

		tagsLiteral := "[]"
		if len(c.Tags) > 0 {
			quoted := make([]string, len(c.Tags))
			for i, t := range c.Tags {
				quoted[i] = fmt.Sprintf(`"%s"`, t)
			}
			tagsLiteral = fmt.Sprintf("[%s]", strings.Join(quoted, ", "))
		}

		w.WriteString(fmt.Sprintf("export const %s = {\n", c.CacheName))
		w.WriteString(fmt.Sprintf("    get: async <T>(%s): Promise<T | null> => {\n", paramStr))
		w.WriteString(fmt.Sprintf("        return cache.get<T>(%s);\n", keyExpr))
		w.WriteString("    },\n")
		w.WriteString(fmt.Sprintf("    set: async <T>(%s, value: T): Promise<void> => {\n", paramStr))
		w.WriteString(fmt.Sprintf("        await cache.set(%s, value, %d, %s);\n", keyExpr, ttlMs, tagsLiteral))
		w.WriteString("    },\n")
		w.WriteString(fmt.Sprintf("    del: async (%s): Promise<void> => {\n", paramStr))
		w.WriteString(fmt.Sprintf("        await cache.del(%s);\n", keyExpr))
		w.WriteString("    },\n")
		w.WriteString("    purge: async (): Promise<void> => {\n")
		w.WriteString(fmt.Sprintf("        await cache.purgeByPrefix(\"%s:\");\n", c.CacheName))
		w.WriteString("    },\n")
		w.WriteString("};\n\n")
	}
	return w.String()
}
