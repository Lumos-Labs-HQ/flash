// GenerateGoCache generates the cache.go file for Go projects
func GenerateGoCache(cfg *config.CacheConfig, packageName string) string {
	var w strings.Builder
	w.WriteString("// Code generated by FlashORM. DO NOT EDIT.\n\n")
	w.WriteString(fmt.Sprintf("package %s\n\n", packageName))
	w.WriteString(`import (
	"context"
	"encoding/json"
	"fmt"
	"os"
	"time"

	"github.com/redis/go-redis/v9"
)

// FlashCache provides Redis-backed caching for FlashORM queries.
type FlashCache struct {
	client *redis.Client
	prefix string
	ctx    context.Context
}

var Cache *FlashCache

func InitCache() {
	url := os.Getenv("` + cfg.RedisURLEnv + `")
	if url == "" {
		url = "redis://localhost:6379"
	}
	opts, err := redis.ParseURL(url)
	if err != nil {
		panic(fmt.Sprintf("flash cache: invalid REDIS_URL: %v", err))
	}
	Cache = &FlashCache{
		client: redis.NewClient(opts),
		prefix: "` + cfg.Prefix + `",
		ctx:    context.Background(),
	}
}

func (c *FlashCache) Get(key string, dest interface{}) bool {
	val, err := c.client.Get(c.ctx, c.prefix+":"+key).Bytes()
	if err != nil {
		return false
	}
	return json.Unmarshal(val, dest) == nil
}

func (c *FlashCache) Set(key string, value interface{}, ttl time.Duration, tags ...string) {
	data, err := json.Marshal(value)
	if err != nil {
		return
	}
	c.client.Set(c.ctx, c.prefix+":"+key, data, ttl)
	for _, tag := range tags {
		c.client.SAdd(c.ctx, c.prefix+":tag:"+tag, key)
	}
}

func (c *FlashCache) Del(key string) {
	c.client.Del(c.ctx, c.prefix+":"+key)
}

func (c *FlashCache) PurgeByTag(tag string) {
	tagKey := c.prefix + ":tag:" + tag
	keys, err := c.client.SMembers(c.ctx, tagKey).Result()
	if err != nil {
		return
	}
	for _, k := range keys {
		c.client.Del(c.ctx, c.prefix+":"+k)
	}
	c.client.Del(c.ctx, tagKey)
}

func (c *FlashCache) PurgeByPrefix(prefix string) {
	pattern := c.prefix + ":" + prefix + "*"
	iter := c.client.Scan(c.ctx, 0, pattern, 100).Iterator()
	for iter.Next(c.ctx) {
		c.client.Del(c.ctx, iter.Val())
	}
}

func (c *FlashCache) Close() {
	c.client.Close()
}
`)
	return w.String()
}

// GenerateGoCacheAccessors generates named cache accessors for Go
func GenerateGoCacheAccessors(caches []*CacheInfo, packageName string, prefix string) string {
	if len(caches) == 0 {
		return ""
	}

	var w strings.Builder
	w.WriteString("// Code generated by FlashORM. DO NOT EDIT.\n\n")
	w.WriteString(fmt.Sprintf("package %s\n\n", packageName))
	w.WriteString("import (\n\t\"fmt\"\n\t\"time\"\n)\n\n")

	// Generate typed CacheTag constants
	allTags := collectUniqueTags(caches)
	if len(allTags) > 0 {
		w.WriteString("// CacheTag represents a cache tag for type-safe purging.\n")
		w.WriteString("type CacheTag string\n\n")
		w.WriteString("// Available cache tags — use with Cache.PurgeTag()\n")
		w.WriteString("const (\n")
		tagConstNames := make([]string, len(allTags))
		for i, tag := range allTags {
			tagConstNames[i] = "Tag" + utils.ToPascalCase(tag)
		}
		// Two distinct tags can PascalCase to the same identifier (e.g.
		// "user-posts" and "user_posts" -> "UserPosts"); dedupe so we never
		// emit two constants with the same name (which would not compile).
		tagConstNames = dedupeNames(tagConstNames)
		for i, tag := range allTags {
			w.WriteString(fmt.Sprintf("\t%s CacheTag = \"%s\"\n", tagConstNames[i], tag))
		}
		w.WriteString(")\n\n")
		w.WriteString("// PurgeTag purges all cache entries associated with the given tag.\n")
		w.WriteString("// Use the typed Tag* constants for safety.\n")
		w.WriteString("func (c *FlashCache) PurgeTag(tag CacheTag) {\n")
		w.WriteString("\tc.PurgeByTag(string(tag))\n")
		w.WriteString("}\n\n")
	}

	for _, cache := range caches {
		accessorName := cache.CacheName
		ttlSec := ParseTTL(cache.TTL)

		// Build function param list
		var paramList, keyParts []string
		for i, p := range cache.KeyParams {
			goType := "interface{}"
			if i < len(cache.KeyTypes) {
				goType = sqlTypeToGoSimple(cache.KeyTypes[i])
			}
			// SafeGoIdent escapes Go keywords ("type" -> "type_") so the
			// generated accessor signature and key expression both compile.
			paramName := utils.SafeGoIdent(utils.ToSnakeCase(p))
			paramList = append(paramList, fmt.Sprintf("%s %s", paramName, goType))
			keyParts = append(keyParts, paramName)
		}
		paramStr := strings.Join(paramList, ", ")
		keyExpr := fmt.Sprintf(`fmt.Sprintf("%s%s", %s)`, accessorName, strings.Repeat(":%v", len(keyParts)), strings.Join(keyParts, ", "))
		if len(keyParts) == 0 {
			keyExpr = fmt.Sprintf(`"%s"`, accessorName)
		} else if len(keyParts) == 1 {
			keyExpr = fmt.Sprintf(`fmt.Sprintf("%s:%%v", %s)`, accessorName, keyParts[0])
		}

		tagsLiteral := "nil"
		if len(cache.Tags) > 0 {
			quoted := make([]string, len(cache.Tags))
			for i, t := range cache.Tags {
				quoted[i] = fmt.Sprintf(`"%s"`, t)
			}
			tagsLiteral = fmt.Sprintf("[]string{%s}", strings.Join(quoted, ", "))
		}

		w.WriteString(fmt.Sprintf("// %s — cache accessor for %s\n", accessorName, cache.QueryName))
		w.WriteString(fmt.Sprintf("var %s = &%sAccessor{}\n\n", accessorName, utils.Uncapitalize(accessorName)))
		w.WriteString(fmt.Sprintf("type %sAccessor struct{}\n\n", utils.Uncapitalize(accessorName)))

		// Get
		w.WriteString(fmt.Sprintf("func (a *%sAccessor) Get(%s) (interface{}, bool) {\n", utils.Uncapitalize(accessorName), paramStr))
		w.WriteString(fmt.Sprintf("\tkey := %s\n", keyExpr))
		w.WriteString("\tvar result interface{}\n")
		w.WriteString("\tif Cache.Get(key, &result) {\n")
		w.WriteString("\t\treturn result, true\n")
		w.WriteString("\t}\n")
		w.WriteString("\treturn nil, false\n")
		w.WriteString("}\n\n")

		// Set
		setParamStr := paramStr
		if setParamStr != "" {
			setParamStr += ", "
		}
		w.WriteString(fmt.Sprintf("func (a *%sAccessor) Set(%svalue interface{}) {\n", utils.Uncapitalize(accessorName), setParamStr))
		w.WriteString(fmt.Sprintf("\tkey := %s\n", keyExpr))
		w.WriteString(fmt.Sprintf("\tCache.Set(key, value, %d*time.Second, %s...)\n", ttlSec, tagsLiteral))
		w.WriteString("}\n\n")

		// Del
		w.WriteString(fmt.Sprintf("func (a *%sAccessor) Del(%s) {\n", utils.Uncapitalize(accessorName), paramStr))
		w.WriteString(fmt.Sprintf("\tkey := %s\n", keyExpr))
		w.WriteString("\tCache.Del(key)\n")
		w.WriteString("}\n\n")

		// Purge (prefix-based)
		w.WriteString(fmt.Sprintf("func (a *%sAccessor) Purge() {\n", utils.Uncapitalize(accessorName)))
		w.WriteString(fmt.Sprintf("\tCache.PurgeByPrefix(\"%s:\")\n", accessorName))
		w.WriteString("}\n\n")
	}
	return w.String()
}

func sqlTypeToGoSimple(sqlType string) string {
	upper := strings.ToUpper(sqlType)
	switch {
	case strings.Contains(upper, "INT"):
		return "int64"
	case strings.Contains(upper, "UUID"):
		return "string"
	case strings.Contains(upper, "TEXT"), strings.Contains(upper, "VARCHAR"):
		return "string"
	case strings.Contains(upper, "BOOL"):
		return "bool"
	default:
		return "interface{}"
	}
}
