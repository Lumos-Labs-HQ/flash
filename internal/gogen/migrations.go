func (g *Generator) generateMigrations() error {
	migrations, err := gencommon.LoadEmbeddedMigrations(g.Config.MigrationsPath)
	if err != nil {
		return fmt.Errorf("load migrations for Go generation: %w", err)
	}

	provider := strings.ToLower(g.Config.Database.Provider)
	if provider == "scylla" || provider == "scylladb" || provider == "cassandra" {
		return g.generateScyllaMigrations(migrations)
	}
	if g.Config.Gen.Go.Driver == "pgx" {
		return g.generatePGXMigrations(migrations)
	}

	var w strings.Builder
	w.WriteString("// Code generated by FlashORM. DO NOT EDIT.\n\n")
	w.WriteString(fmt.Sprintf("package %s\n\n", filepath.Base(g.Config.Gen.Go.Out)))
	w.WriteString("import (\n\t\"context\"\n\t\"database/sql\"\n\t\"fmt\"\n)\n\n")
	w.WriteString("type flashEmbeddedMigration struct {\n\tid string\n\tname string\n\tchecksum string\n\tstatements []string\n}\n\n")
	writeGoMigrationSlice(&w, migrations)

	createSQL, selectSQL, insertSQL := goMigrationSQL(provider)
	w.WriteString("// FlashInitMigrate applies pending migrations embedded by flash gen.\n")
	w.WriteString("// It uses the application's database connection and never invokes the Flash binary.\n")
	w.WriteString("func FlashInitMigrate(ctx context.Context, db *sql.DB) error {\n")
	w.WriteString(fmt.Sprintf("\tif _, err := db.ExecContext(ctx, %s); err != nil {\n\t\treturn fmt.Errorf(\"create migration table: %%w\", err)\n\t}\n", strconv.Quote(createSQL)))
	w.WriteString(fmt.Sprintf("\trows, err := db.QueryContext(ctx, %s)\n", strconv.Quote(selectSQL)))
	w.WriteString("\tif err != nil { return fmt.Errorf(\"read applied migrations: %w\", err) }\n")
	w.WriteString("\tapplied := make(map[string]string)\n\tfor rows.Next() {\n\t\tvar id, checksum string\n\t\tif err := rows.Scan(&id, &checksum); err != nil { rows.Close(); return err }\n\t\tapplied[id] = checksum\n\t}\n\tif err := rows.Close(); err != nil { return err }\n\tif err := rows.Err(); err != nil { return err }\n\n")
	w.WriteString("\tfor _, migration := range flashEmbeddedMigrations {\n")
	w.WriteString("\t\tif checksum, ok := applied[migration.id]; ok {\n\t\t\tif checksum != migration.checksum { return fmt.Errorf(\"applied migration %s checksum mismatch\", migration.id) }\n\t\t\tcontinue\n\t\t}\n")
	if provider == "clickhouse" {
		w.WriteString("\t\tfor _, statement := range migration.statements {\n\t\t\tif _, err := db.ExecContext(ctx, statement); err != nil { return fmt.Errorf(\"migration %s: %w\", migration.id, err) }\n\t\t}\n")
		w.WriteString(fmt.Sprintf("\t\tif _, err := db.ExecContext(ctx, %s, migration.id, migration.name, migration.checksum); err != nil { return fmt.Errorf(\"record migration %%s: %%w\", migration.id, err) }\n", strconv.Quote(insertSQL)))
	} else {
		w.WriteString("\t\ttx, err := db.BeginTx(ctx, nil)\n\t\tif err != nil { return fmt.Errorf(\"begin migration %s: %w\", migration.id, err) }\n")
		w.WriteString("\t\tfor _, statement := range migration.statements {\n\t\t\tif _, err := tx.ExecContext(ctx, statement); err != nil { _ = tx.Rollback(); return fmt.Errorf(\"migration %s: %w\", migration.id, err) }\n\t\t}\n")
		w.WriteString(fmt.Sprintf("\t\tif _, err := tx.ExecContext(ctx, %s, migration.id, migration.name, migration.checksum); err != nil { _ = tx.Rollback(); return fmt.Errorf(\"record migration %%s: %%w\", migration.id, err) }\n", strconv.Quote(insertSQL)))
		w.WriteString("\t\tif err := tx.Commit(); err != nil { return fmt.Errorf(\"commit migration %s: %w\", migration.id, err) }\n")
	}
	w.WriteString("\t}\n\treturn nil\n}\n")

	return os.WriteFile(filepath.Join(g.Config.Gen.Go.Out, "migrations.go"), []byte(w.String()), 0644)
}

func (g *Generator) generatePGXMigrations(migrations []gencommon.EmbeddedMigration) error {
	createSQL, selectSQL, insertSQL := goMigrationSQL("postgresql")
	var w strings.Builder
	w.WriteString("// Code generated by FlashORM. DO NOT EDIT.\n\n")
	w.WriteString(fmt.Sprintf("package %s\n\n", filepath.Base(g.Config.Gen.Go.Out)))
	w.WriteString("import (\n\t\"context\"\n\t\"fmt\"\n\n\t\"github.com/jackc/pgx/v5/pgxpool\"\n)\n\n")
	w.WriteString("type flashEmbeddedMigration struct { id, name, checksum string; statements []string }\n\n")
	writeGoMigrationSlice(&w, migrations)
	w.WriteString("// FlashInitMigrate applies pending migrations embedded by flash gen.\n")
	w.WriteString("// It uses the application's pgx pool and never invokes the Flash binary.\n")
	w.WriteString("func FlashInitMigrate(ctx context.Context, pool *pgxpool.Pool) error {\n")
	w.WriteString(fmt.Sprintf("\tif _, err := pool.Exec(ctx, %s); err != nil { return fmt.Errorf(\"create migration table: %%w\", err) }\n", strconv.Quote(createSQL)))
	w.WriteString(fmt.Sprintf("\trows, err := pool.Query(ctx, %s)\n", strconv.Quote(selectSQL)))
	w.WriteString("\tif err != nil { return fmt.Errorf(\"read applied migrations: %w\", err) }\n")
	w.WriteString("\tapplied := make(map[string]string)\n\tfor rows.Next() { var id, checksum string; if err := rows.Scan(&id, &checksum); err != nil { rows.Close(); return err }; applied[id] = checksum }\n\trows.Close()\n\tif err := rows.Err(); err != nil { return err }\n")
	w.WriteString("\tfor _, migration := range flashEmbeddedMigrations {\n\t\tif checksum, ok := applied[migration.id]; ok { if checksum != migration.checksum { return fmt.Errorf(\"applied migration %s checksum mismatch\", migration.id) }; continue }\n")
	w.WriteString("\t\ttx, err := pool.Begin(ctx)\n\t\tif err != nil { return fmt.Errorf(\"begin migration %s: %w\", migration.id, err) }\n")
	w.WriteString("\t\tfor _, statement := range migration.statements { if _, err := tx.Exec(ctx, statement); err != nil { _ = tx.Rollback(ctx); return fmt.Errorf(\"migration %s: %w\", migration.id, err) } }\n")
	w.WriteString(fmt.Sprintf("\t\tif _, err := tx.Exec(ctx, %s, migration.id, migration.name, migration.checksum); err != nil { _ = tx.Rollback(ctx); return fmt.Errorf(\"record migration %%s: %%w\", migration.id, err) }\n", strconv.Quote(insertSQL)))
	w.WriteString("\t\tif err := tx.Commit(ctx); err != nil { return fmt.Errorf(\"commit migration %s: %w\", migration.id, err) }\n\t}\n\treturn nil\n}\n")
	return os.WriteFile(filepath.Join(g.Config.Gen.Go.Out, "migrations.go"), []byte(w.String()), 0644)
}

func writeGoMigrationSlice(w *strings.Builder, migrations []gencommon.EmbeddedMigration) {
	w.WriteString("var flashEmbeddedMigrations = []flashEmbeddedMigration{\n")
	for _, migration := range migrations {
		w.WriteString(fmt.Sprintf("\t{id: %s, name: %s, checksum: %s, statements: []string{\n", strconv.Quote(migration.ID), strconv.Quote(migration.Name), strconv.Quote(migration.Checksum)))
		for _, statement := range migration.Statements {
			if strings.TrimSpace(statement) != "" {
				w.WriteString("\t\t" + strconv.Quote(statement) + ",\n")
			}
		}
		w.WriteString("\t}},\n")
	}
	w.WriteString("}\n\n")
}

func goMigrationSQL(provider string) (create, selectApplied, insert string) {
	selectApplied = "SELECT id, checksum FROM _flash_migrations WHERE finished_at IS NOT NULL ORDER BY started_at"
	switch provider {
	case "postgres", "postgresql", "":
		create = "CREATE TABLE IF NOT EXISTS _flash_migrations (id VARCHAR(255) PRIMARY KEY, checksum VARCHAR(64) NOT NULL, finished_at TIMESTAMP WITH TIME ZONE, migration_name VARCHAR(255) NOT NULL, logs TEXT, rolled_back_at TIMESTAMP WITH TIME ZONE, started_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(), applied_steps_count INTEGER NOT NULL DEFAULT 0)"
		insert = "INSERT INTO _flash_migrations (id, migration_name, checksum, started_at, finished_at, applied_steps_count) VALUES ($1, $2, $3, NOW(), NOW(), 1)"
	case "mysql":
		create = "CREATE TABLE IF NOT EXISTS _flash_migrations (id VARCHAR(255) PRIMARY KEY, checksum VARCHAR(64) NOT NULL, finished_at TIMESTAMP NULL, migration_name VARCHAR(255) NOT NULL, logs TEXT, rolled_back_at TIMESTAMP NULL, started_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, applied_steps_count INTEGER NOT NULL DEFAULT 0) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4"
		insert = "INSERT INTO _flash_migrations (id, migration_name, checksum, started_at, finished_at, applied_steps_count) VALUES (?, ?, ?, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP, 1)"
	case "clickhouse":
		create = "CREATE TABLE IF NOT EXISTS _flash_migrations (id String, migration_name String, checksum String, started_at DateTime DEFAULT now(), finished_at Nullable(DateTime), applied_steps_count UInt32 DEFAULT 0) ENGINE = ReplacingMergeTree() ORDER BY id"
		insert = "INSERT INTO _flash_migrations (id, migration_name, checksum, started_at, finished_at, applied_steps_count) VALUES (?, ?, ?, now(), now(), 1)"
	default: // SQLite
		create = "CREATE TABLE IF NOT EXISTS _flash_migrations (id TEXT PRIMARY KEY, checksum TEXT NOT NULL, finished_at TIMESTAMP, migration_name TEXT NOT NULL, logs TEXT, rolled_back_at TIMESTAMP, started_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, applied_steps_count INTEGER NOT NULL DEFAULT 0)"
		insert = "INSERT INTO _flash_migrations (id, migration_name, checksum, started_at, finished_at, applied_steps_count) VALUES (?, ?, ?, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP, 1)"
	}
	return create, selectApplied, insert
}

func (g *Generator) generateScyllaMigrations(migrations []gencommon.EmbeddedMigration) error {
	importPath := "github.com/apache/cassandra-gocql-driver/v2"
	execCall := "session.Query(statement).ExecContext(ctx)"
	queryCall := "session.Query(\"SELECT id, checksum FROM \\\"_flash_migrations\\\"\").IterContext(ctx)"
	insertCall := "session.Query(`INSERT INTO \"_flash_migrations\" (id, migration_name, checksum, started_at, finished_at, applied_steps_count) VALUES (?, ?, ?, ?, ?, 1)`, migration.id, migration.name, migration.checksum, now, now).ExecContext(ctx)"
	if g.Config.Gen.Go.Driver == "gocql" {
		importPath = "github.com/gocql/gocql"
		execCall = "session.Query(statement).WithContext(ctx).Exec()"
		queryCall = "session.Query(\"SELECT id, checksum FROM \\\"_flash_migrations\\\"\").WithContext(ctx).Iter()"
		insertCall = "session.Query(`INSERT INTO \"_flash_migrations\" (id, migration_name, checksum, started_at, finished_at, applied_steps_count) VALUES (?, ?, ?, ?, ?, 1)`, migration.id, migration.name, migration.checksum, now, now).WithContext(ctx).Exec()"
	}

	var w strings.Builder
	w.WriteString("// Code generated by FlashORM. DO NOT EDIT.\n\n")
	w.WriteString(fmt.Sprintf("package %s\n\n", filepath.Base(g.Config.Gen.Go.Out)))
	w.WriteString(fmt.Sprintf("import (\n\t\"context\"\n\t\"fmt\"\n\t\"time\"\n\n\t%q\n)\n\n", importPath))
	w.WriteString("type flashEmbeddedMigration struct { id, name, checksum string; statements []string }\n\n")
	writeGoMigrationSlice(&w, migrations)
	w.WriteString("// FlashInitMigrate applies embedded migrations without invoking the Flash binary.\n")
	w.WriteString("func FlashInitMigrate(ctx context.Context, session *gocql.Session) error {\n")
	createCall := "session.Query(`CREATE TABLE IF NOT EXISTS \"_flash_migrations\" (id text, migration_name text, checksum text, started_at timestamp, finished_at timestamp, applied_steps_count int, PRIMARY KEY (id))`).ExecContext(ctx)"
	if g.Config.Gen.Go.Driver == "gocql" {
		createCall = "session.Query(`CREATE TABLE IF NOT EXISTS \"_flash_migrations\" (id text, migration_name text, checksum text, started_at timestamp, finished_at timestamp, applied_steps_count int, PRIMARY KEY (id))`).WithContext(ctx).Exec()"
	}
	w.WriteString(fmt.Sprintf("\tif err := %s; err != nil { return err }\n", createCall))
	w.WriteString(fmt.Sprintf("\titer := %s\n", queryCall))
	w.WriteString("\tapplied := make(map[string]string)\n\tvar id, checksum string\n\tfor iter.Scan(&id, &checksum) { applied[id] = checksum }\n\tif err := iter.Close(); err != nil { return err }\n")
	w.WriteString("\tfor _, migration := range flashEmbeddedMigrations {\n\t\tif checksum, ok := applied[migration.id]; ok { if checksum != migration.checksum { return fmt.Errorf(\"applied migration %s checksum mismatch\", migration.id) }; continue }\n")
	w.WriteString(fmt.Sprintf("\t\tfor _, statement := range migration.statements { if err := %s; err != nil { return fmt.Errorf(\"migration %%s: %%w\", migration.id, err) } }\n", execCall))
	w.WriteString("\t\tnow := time.Now()\n")
	w.WriteString(fmt.Sprintf("\t\tif err := %s; err != nil { return err }\n", insertCall))
	w.WriteString("\t}\n\treturn nil\n}\n")
	return os.WriteFile(filepath.Join(g.Config.Gen.Go.Out, "migrations.go"), []byte(w.String()), 0644)
}
