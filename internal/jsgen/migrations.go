package jsgen

import (
	"fmt"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"github.com/Lumos-Labs-HQ/flash/internal/gencommon"
)

func (g *Generator) generateMigrations() error {
	migrations, err := gencommon.LoadEmbeddedMigrations(g.Config.MigrationsPath)
	if err != nil {
		return fmt.Errorf("load migrations for JS generation: %w", err)
	}
	var w strings.Builder
	w.WriteString("// Code generated by FlashORM. DO NOT EDIT.\n\n")
	w.WriteString("const migrations = [\n")
	for _, m := range migrations {
		w.WriteString(fmt.Sprintf("  { id: %s, name: %s, checksum: %s, statements: [", strconv.Quote(m.ID), strconv.Quote(m.Name), strconv.Quote(m.Checksum)))
		for i, s := range m.Statements {
			if i > 0 {
				w.WriteString(", ")
			}
			w.WriteString(strconv.Quote(s))
		}
		w.WriteString("] },\n")
	}
	w.WriteString("];\n\n")
	async := g.Config.Gen.JS.Driver != "better-sqlite3" && g.Config.Gen.JS.Driver != "bun:sqlite"
	w.WriteString("// FlashInitMigrate applies embedded migrations without invoking the Flash binary.\n")
	if async {
		w.WriteString("async function FlashInitMigrate(db) {\n")
		w.WriteString("  await db.query(`CREATE TABLE IF NOT EXISTS _flash_migrations (id VARCHAR(255) PRIMARY KEY, checksum VARCHAR(64) NOT NULL, finished_at TIMESTAMP NULL, migration_name VARCHAR(255) NOT NULL, started_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)`);\n")
		w.WriteString("  const applied = await db.query(`SELECT id, checksum FROM _flash_migrations WHERE finished_at IS NOT NULL`);\n")
		w.WriteString("  const known = new Map(applied.rows.map(row => [row.id, row.checksum]));\n")
		w.WriteString("  for (const migration of migrations) { if (known.has(migration.id)) { if (known.get(migration.id) !== migration.checksum) throw new Error(`applied migration ${migration.id} checksum mismatch`); continue; }\n")
		w.WriteString("    for (const statement of migration.statements) await db.query(statement);\n")
		w.WriteString("    await db.query(`INSERT INTO _flash_migrations (id, migration_name, checksum, started_at, finished_at) VALUES ($1, $2, $3, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP)`, [migration.id, migration.name, migration.checksum]);\n  }\n  return undefined;\n}\n\nmodule.exports = { FlashInitMigrate };\n")
	} else {
		w.WriteString("function FlashInitMigrate(db) {\n")
		w.WriteString("  db.exec(`CREATE TABLE IF NOT EXISTS _flash_migrations (id TEXT PRIMARY KEY, checksum TEXT NOT NULL, finished_at TIMESTAMP, migration_name TEXT NOT NULL, started_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)`);\n")
		w.WriteString("  const known = new Map(db.prepare(`SELECT id, checksum FROM _flash_migrations WHERE finished_at IS NOT NULL`).all().map(row => [row.id, row.checksum]));\n")
		w.WriteString("  for (const migration of migrations) { if (known.has(migration.id)) { if (known.get(migration.id) !== migration.checksum) throw new Error(`applied migration ${migration.id} checksum mismatch`); continue; } for (const statement of migration.statements) db.exec(statement); db.prepare(`INSERT INTO _flash_migrations (id, migration_name, checksum, started_at, finished_at) VALUES (?, ?, ?, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP)`).run(migration.id, migration.name, migration.checksum); }\n}\n\nmodule.exports = { FlashInitMigrate };\n")
	}
	return os.WriteFile(filepath.Join(g.Config.Gen.JS.Out, "migrations.js"), []byte(w.String()), 0644)
}
